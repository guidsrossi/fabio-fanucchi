function normalizarNome(valor: unknown) {
  return String(valor || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, ' ')
    .trim();
}

export function frequenciaAnualConselho(
  ano: number,
  bimestre: number,
  turma: string,
  nome: string
) {
  if (ano !== 2026 || bimestre !== 2) return '';

  const frequenciasDaTurma = FREQUENCIAS_2026_2[String(turma || '').trim().toUpperCase()];
  if (!frequenciasDaTurma) return '';

  const nomeNormalizado = normalizarNome(nome);
  const frequenciaExata = frequenciasDaTurma[nomeNormalizado];
  if (frequenciaExata) return frequenciaExata;

  const correspondencias = Object.entries(frequenciasDaTurma).filter(
    ([nomeDaPlanilha]) =>
      nomeDaPlanilha.includes(nomeNormalizado) || nomeNormalizado.includes(nomeDaPlanilha)
  );

  return correspondencias.length === 1 ? correspondencias[0][1] : '';
}
